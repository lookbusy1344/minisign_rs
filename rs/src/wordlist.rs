//! PGP Word List encoding for human-readable key fingerprints
//!
//! The PGP Word List is a phonetically distinct word list designed for conveying
//! data bytes via voice channels. Each byte value (0x00-0xFF) maps to two different
//! words depending on whether it appears at an even or odd position in the byte sequence.
//!
//! This positional encoding helps detect transposition errors when bytes are swapped.
//!
//! ## References
//!
//! - <https://en.wikipedia.org/wiki/PGP_word_list>
//! - <https://philzimmermann.com/docs/PGP_word_list.pdf>

