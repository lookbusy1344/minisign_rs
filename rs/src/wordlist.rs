// Compile-time invariant: both word lists must cover all 256 byte values.
// Although [&str; 256] already encodes the length in the type, these assertions
// make the requirement explicit and will catch a future type change (e.g. to
// &[&str]) before it silently breaks the runtime coverage test.
const _: () = assert!(
    EVEN_WORDS.len() == 256,
    "EVEN_WORDS must have exactly 256 entries"
);
const _: () = assert!(
    ODD_WORDS.len() == 256,
    "ODD_WORDS must have exactly 256 entries"
);

/// Convert a byte slice to PGP Word List representation
///
/// Each byte is converted to a word from either the even or odd word list
/// depending on its position in the input slice (0-indexed).
///
/// # Arguments
///
/// * `bytes` - The byte slice to convert
///
/// # Returns
///
/// A string containing space-separated words representing the input bytes
///
/// # Examples
///
/// ```
/// use minisign::wordlist::bytes_to_words;
///
/// // First byte (position 0, even) -> "aardvark"
/// // Second byte (position 1, odd) -> "adviser"
/// let bytes = [0x00, 0x01];
/// let words = bytes_to_words(&bytes);
/// assert_eq!(words, "aardvark adviser");
/// ```
#[must_use]
pub fn bytes_to_words(bytes: &[u8]) -> String {
    bytes
        .iter()
        .enumerate()
        .map(|(i, &byte)| {
            if i % 2 == 0 {
                EVEN_WORDS[usize::from(byte)]
            } else {
                ODD_WORDS[usize::from(byte)]
            }
        })
        .collect::<Vec<&str>>()
        .join(" ")
}

/// Convert a `KeyNum` (8-byte key identifier) to PGP Word List representation
///
/// This is a convenience wrapper around `bytes_to_words` for `KeyNum` types,
/// producing exactly 8 words (one per byte).
///
/// # Arguments
///
/// * `keynum` - The key number to convert
///
/// # Returns
///
/// A string containing 8 space-separated words representing the key ID
///
/// # Examples
///
/// ```no_run
/// use minisign::crypto::KeyNum;
/// use minisign::wordlist::keynum_to_words;
///
/// let keynum = KeyNum::from_bytes([0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07]);
/// let words = keynum_to_words(&keynum);
/// // Produces 8 words
/// assert_eq!(words.split_whitespace().count(), 8);
/// ```
#[must_use]
pub fn keynum_to_words(keynum: &KeyNum) -> String {
    bytes_to_words(keynum.as_bytes())
}
